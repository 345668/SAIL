"use server"
import { redirect } from "next/navigation"
import { getSession } from "@/lib/auth"
import { ControlError } from "@/lib/tenant-control"
import { applyHierarchy, decide, describePlan, mergePair, planPair, reopen, runDetectionNow, undoPair } from "@/lib/directory-identity"

const fail = (e: unknown) => `err=${encodeURIComponent(e instanceof ControlError ? e.message : "Something went wrong. Nothing was changed.")}`
const back = (f: FormData, q: string) => redirect(`/directory-identity?kind=${encodeURIComponent(String(f.get("kind") || "firm"))}&tier=${encodeURIComponent(String(f.get("tier") || ""))}&status=${encodeURIComponent(String(f.get("status") || "open"))}&page=${encodeURIComponent(String(f.get("page") || "0"))}&${q}`)

export async function decideAction(f: FormData) {
  const s = await getSession(); if (!s) redirect("/login")
  let q = "ok=Recorded."
  try { await decide(s, Number(f.get("id")), String(f.get("decision") || ""), { parentId: String(f.get("parent") || "") || undefined, reason: String(f.get("reason") || "") }) } catch (e) { q = fail(e) }
  back(f, q)
}
export async function reopenAction(f: FormData) {
  const s = await getSession(); if (!s) redirect("/login")
  let q = "ok=Reopened."
  try { await reopen(s, Number(f.get("id")), String(f.get("reason") || "")) } catch (e) { q = fail(e) }
  back(f, q)
}
export async function runNow(f: FormData) {
  const s = await getSession(); if (!s) redirect("/login")
  let q = ""
  try { const r = await runDetectionNow(s); q = `ok=${encodeURIComponent(`Detection finished: ${r.firms.toLocaleString()} firm pairs and ${r.people.toLocaleString()} person pairs found.`)}` } catch (e) { q = fail(e) }
  back(f, q)
}

export async function previewAction(f: FormData) {
  const s = await getSession(); if (!s) redirect("/login")
  let q: string
  try { q = `ok=${encodeURIComponent(describePlan(await planPair(s, Number(f.get("id")), String(f.get("survivor") || ""))))}` } catch (e) { q = fail(e) }
  back(f, q)
}
export async function mergeAction(f: FormData) {
  const s = await getSession(); if (!s) redirect("/login")
  let q: string
  try { const r = await mergePair(s, Number(f.get("id")), String(f.get("survivor") || ""), String(f.get("reason") || "")); q = `ok=${encodeURIComponent(`Merged. ${r.moved} reference(s) moved${r.filled.length ? `, filled: ${r.filled.join(", ")}` : ""}${r.conflicts.length ? `; kept the survivor's value for: ${r.conflicts.join(", ")}` : ""}. You can undo it for 90 days under "merged".`)}` } catch (e) { q = fail(e) }
  back(f, q)
}
export async function undoAction(f: FormData) {
  const s = await getSession(); if (!s) redirect("/login")
  let q: string
  try { const r = await undoPair(s, Number(f.get("id")), String(f.get("reason") || "")); q = `ok=${encodeURIComponent(`Put back. ${r.moved} reference(s) moved back${r.fieldsKept.length ? `; kept as edited since: ${r.fieldsKept.join(", ")}` : ""}${r.derivedNotRestored ? `; ${r.derivedNotRestored} derived result row(s) will be regenerated by the next run` : ""}.`)}` } catch (e) { q = fail(e) }
  back(f, q)
}
export async function hierarchyAction(f: FormData) {
  const s = await getSession(); if (!s) redirect("/login")
  let q = "ok=Applied: the child is now a programme of the parent."
  try { await applyHierarchy(s, Number(f.get("id"))) } catch (e) { q = fail(e) }
  back(f, q)
}
